def chapter_file(chapter_id: int) -> Path:
    matches = list(ROOT.glob(f"manuscript/volume-*/C{chapter_id:02d}-*/chapter.md"))
    if len(matches) != 1:
        raise SystemExit(f"C{chapter_id:02d}: expected one chapter, got {matches}")
    return matches[0]


def main() -> None:
    changed = 0
    for chapter_id, (title, body) in SLICES.items():
        path = chapter_file(chapter_id)
        text = path.read_text(encoding="utf-8")
        if MARKER in text:
            continue
        match = re.search(r"^\*\*图\s+\d+-\d+", text, flags=re.MULTILINE)
        if not match:
            raise SystemExit(f"{path}: no formal figure anchor")
        block = (
            f"{MARKER}\n\n"
            f"### 现场切片：{title}\n\n"
            f"{body}\n\n"
        )
        text = text[: match.start()] + block + text[match.start() :]
        path.write_text(text, encoding="utf-8")
        changed += 1
    print(f"opening slices inserted: {changed}; total required: {len(SLICES)}")


if __name__ == "__main__":
    main()
